"""Render P04 requirement snapshots as disposable human-readable and JSON reports.

No independent status state exists here. A checked box asserts implementation and
verification evidence only, never independent product-policy approval.
"""

from __future__ import annotations

import html
import json
import os
import tempfile
from collections.abc import Mapping
from pathlib import Path
from typing import Any

MARKDOWN_NAME = "REQUIREMENTS_STATUS.md"
JSON_NAME = "REQUIREMENTS_STATUS.json"
MARKER = "<!-- Generated by DevFlow requirements report; do not edit. -->"
AXES = ("implementation", "difference", "decision", "verification")
GAP_LABELS = (
    ("original_without_prd", "Original requirements missing from PRD"),
    ("prd_without_plan", "PRD requirements missing from PLAN"),
    ("work_without_prd", "WORK requirements missing from PRD"),
    ("unmapped_acceptance", "Unmapped acceptance criteria"),
    ("unlisted_work", "WORK not listed by PLAN"),
)


def _snapshot_rows(snapshot: Mapping[str, Any]) -> list[dict[str, Any]]:
    if snapshot.get("schema_version") != 1:
        raise ValueError("Unsupported requirement snapshot schema_version")
    rows = snapshot.get("requirements")
    if not isinstance(rows, list):
        raise ValueError("Requirement snapshot has no requirements list")
    if not isinstance(snapshot.get("diagnostics"), dict):
        raise ValueError("Requirement snapshot has no diagnostics")
    if not isinstance(snapshot.get("gaps"), dict):
        raise ValueError("Requirement snapshot has no traceability gaps")
    for row in rows:
        if not isinstance(row, dict) or not isinstance(row.get("id"), str) or not all(
            isinstance(row.get(axis), str) and row[axis] for axis in AXES
        ):
            raise ValueError("Requirement snapshot has an invalid requirement row")
    return rows


def _safe(value: Any) -> str:
    """Avoid accidental Markdown structure or HTML from untrusted PRD and PLAN text."""
    clean = " ".join(str(value).split())
    clean = html.escape(clean, quote=False)
    for character in ("\\", "`", "*", "_", "[", "]", "|", "#"):
        clean = clean.replace(character, "\\" + character)
    return clean


def _values(values: Any) -> str:
    if not isinstance(values, list) or not values:
        return "none"
    return ", ".join(_safe(value) for value in values)


def _line_check(row: Mapping[str, Any]) -> str:
    # A checked box means tested implementation, not a final product sign-off.
    complete = (
        row.get("scope") not in {"excluded", "deferred", "cancelled"}
        and row["implementation"] == "implemented"
        and row["verification"] == "passed"
    )
    return "x" if complete else " "


def render_markdown(snapshot: Mapping[str, Any]) -> str:
    """Render one canonical checklist plus derived exception views; never alter snapshot."""
    rows = _snapshot_rows(snapshot)
    diagnostics = snapshot["diagnostics"]
    errors = diagnostics.get("errors") or []
    warnings = diagnostics.get("warnings") or []
    gaps = snapshot["gaps"]
    done = sum(_line_check(row) == "x" for row in rows)
    in_scope = sum(row.get("scope") not in {"excluded", "deferred", "cancelled"} for row in rows)
    lines = [
        MARKER,
        f"# Requirements Status — {_safe(snapshot.get('domain', 'unknown'))}",
        "",
        "Derived from current PRD, PLAN, WORK, decisions, and evidence. "
        "`[x]` means **implemented and verification passed**; it does **not** mean "
        "product-policy approval or original-requirement alignment.",
        "",
        f"- HEAD: `{_safe(snapshot.get('head_sha') or 'unknown')}`",
        f"- Requirements: **{len(rows)}** (in scope: **{in_scope}**)",
        f"- Verified implementations: **{done}/{in_scope}** in scope",
        f"- Diagnostics: **{len(errors)} errors**, **{len(warnings)} warnings**",
        "",
        "## Status by dimension",
        "",
        "| Dimension | Status | Requirements |",
        "| --- | --- | ---: |",
    ]
    for axis in AXES:
        counts: dict[str, int] = {}
        for row in rows:
            value = row[axis]
            counts[value] = counts.get(value, 0) + 1
        for key in sorted(counts):
            lines.append(f"| {_safe(axis)} | {_safe(key)} | {counts[key]} |")
    if not rows:
        lines.append("| — | unknown | 0 |")
    lines.extend(["", "## Requirement checklist", ""])
    if not rows:
        lines.append("- No requirement IDs were detected. Review diagnostics before assuming scope is empty.")
    for row in rows:
        heading = _safe(row["id"])
        if row.get("title"):
            heading += " — " + _safe(row["title"])
        lines.append(
            f"- [{_line_check(row)}] **{heading}** — "
            f"implementation: `{_safe(row['implementation'])}`; "
            f"original: `{_safe(row['difference'])}`; "
            f"policy: `{_safe(row['decision'])}`; "
            f"verification: `{_safe(row['verification'])}`"
        )
        lines.append(
            f"  - Scope: `{_safe(row.get('scope', 'unknown'))}`; "
            f"WORK: {_values(row.get('work_ids'))}; "
            f"acceptance: {_values(row.get('acceptance_ids'))}"
        )
        sources = row.get("source_refs")
        if isinstance(sources, list) and sources:
            locations = [
                f"{source.get('source', '?')} {source.get('lines', '?')} ({source.get('disposition', '?')})"
                for source in sources if isinstance(source, dict)
            ]
            if locations:
                lines.append("  - Sources: " + _values(locations))
        decisions = [*row.get("technical_decisions", []), *row.get("policy_decisions", [])]
        if decisions:
            lines.append("  - Decisions: " + _values(decisions))
        work_statuses = row.get("works")
        if isinstance(work_statuses, list) and work_statuses:
            visible_work = [
                f"{work['id']}: {work.get('status', 'unknown')}"
                for work in work_statuses if isinstance(work, dict) and 'id' in work
            ]
            if visible_work:
                lines.append("  - WORK status: " + _values(visible_work))
        if row.get("unmapped_acceptance_ids"):
            lines.append("  - Missing acceptance links: " + _values(row["unmapped_acceptance_ids"]))
        if row.get("blocking_decisions"):
            lines.append("  - Blocking decisions: " + _values(row["blocking_decisions"]))
    lines.extend(["", "## Attention queues", ""])
    queues = (
        ("Policy approval required", lambda r: r["decision"] in {"pending", "provisional", "rejected"}, "decision"),
        ("Different from original", lambda r: r["difference"] in {"technical_deviation", "policy_deviation"}, "difference"),
        ("Original comparison unverified", lambda r: r["difference"] == "unknown" and r.get("scope") not in {"excluded", "deferred", "cancelled"}, "difference"),
        ("Verification failed or stale", lambda r: r["verification"] in {"failed", "stale"}, "verification"),
        ("Implementation or verification outstanding", lambda r: _line_check(r) != "x" and r.get("scope") not in {"excluded", "deferred", "cancelled"}, "verification"),
        ("Transferred requirements", lambda r: r.get("scope") == "transferred", "scope"),
        ("Explicitly excluded, deferred or cancelled", lambda r: r.get("scope") in {"excluded", "deferred", "cancelled"}, "scope"),
    )
    for title, predicate, field in queues:
        lines.extend([f"### {title}", ""])
        selected = [row for row in rows if predicate(row)]
        if not selected:
            lines.append("- None in this snapshot.")
        else:
            for row in selected:
                decisions = row.get("policy_decisions") or row.get("technical_decisions") or []
                context = "; decisions: " + _values(decisions) if decisions else ""
                lines.append(
                    f"- [ ] {_safe(row['id'])}: `{_safe(row.get(field, 'unknown'))}`{context}"
                )
        lines.append("")
    lines.extend(["## Traceability gaps", ""])
    any_gap = False
    for key, title in GAP_LABELS:
        value = gaps.get(key)
        if not value:
            continue
        any_gap = True
        lines.append(f"### {title}")
        lines.append("")
        if isinstance(value, list):
            lines.extend(f"- [ ] {_safe(item)}" for item in value)
        elif isinstance(value, dict):
            for req, items in sorted(value.items()):
                lines.append(f"- [ ] {_safe(req)}: {_values(items)}")
        else:
            lines.append(f"- [ ] {_safe(value)}")
        lines.append("")
    if not any_gap:
        lines.append("- No traceability gaps detected in this snapshot.")
        lines.append("")
    lines.extend(["## Diagnostics", ""])
    for name, entries in (("Errors", errors), ("Warnings", warnings)):
        lines.append(f"### {name}")
        lines.append("")
        if isinstance(entries, list) and entries:
            lines.extend(f"- {_safe(entry)}" for entry in entries)
        else:
            lines.append("- None recorded.")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_json(snapshot: Mapping[str, Any]) -> str:
    """Preserve every field of the canonical P04 snapshot; no derived status overrides."""
    _snapshot_rows(snapshot)
    return json.dumps(snapshot, ensure_ascii=False, indent=2) + "\n"


def _stage_bytes(directory: Path, data: bytes) -> Path:
    fd, name = tempfile.mkstemp(prefix=".requirements-status-", dir=directory)
    path = Path(name)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(data)
    except BaseException:
        path.unlink(missing_ok=True)
        raise
    return path


def write_pair(domain: Path, snapshot: Mapping[str, Any]) -> tuple[Path, Path]:
    """Replace both derived files; restore original pair after a failed replacement."""
    markdown = render_markdown(snapshot).encode("utf-8")
    raw_json = render_json(snapshot).encode("utf-8")
    if domain.is_symlink() or not domain.is_dir():
        raise ValueError("Requirements report domain must be a real directory")
    destinations = ((domain / MARKDOWN_NAME, markdown), (domain / JSON_NAME, raw_json))
    for target, _ in destinations:
        if target.is_symlink() or (target.exists() and not target.is_file()):
            raise ValueError(f"Requirements report target cannot be a symlink or directory: {target}")
    old: dict[Path, bytes | None] = {
        target: target.read_bytes() if target.exists() else None for target, _ in destinations
    }
    staged: dict[Path, Path] = {}
    committed: list[Path] = []
    try:
        for target, value in destinations:
            if old[target] != value:
                staged[target] = _stage_bytes(domain, value)
        for target, _ in destinations:
            if target not in staged:
                continue
            if target.is_symlink():
                raise ValueError(f"Requirements report target became a symlink: {target}")
            os.replace(staged[target], target)
            staged.pop(target)
            committed.append(target)
    except BaseException:
        failures: list[str] = []
        for target in reversed(committed):
            try:
                previous = old[target]
                if previous is None:
                    target.unlink(missing_ok=True)
                else:
                    rollback = _stage_bytes(domain, previous)
                    try:
                        os.replace(rollback, target)
                    finally:
                        rollback.unlink(missing_ok=True)
            except OSError as exc:
                failures.append(f"{target.name}: {exc}")
        if failures:
            raise RuntimeError("Requirement report rollback failed: " + "; ".join(failures))
        raise
    finally:
        for remaining in staged.values():
            remaining.unlink(missing_ok=True)
    return destinations[0][0], destinations[1][0]
